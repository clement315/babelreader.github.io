const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const model=require('../assets/classics-editor.js');
const original=JSON.parse(fs.readFileSync(path.join(__dirname,'../data/classics/parmenides/126.json'),'utf8'));
const unit=original.units[0],backup=model.empty('parmenides');
backup.units[unit.id]={ref:unit.ref,greek:unit.greek,reading:{...model.base(unit),zh:'馆主自行修改的译文',structure:'馆主自行修改的结构分析'}};
const validated=model.validate(JSON.parse(JSON.stringify(backup)),'parmenides');
const patched=model.patchPage(original,validated);
assert.equal(patched.units[0].reading.zh,'馆主自行修改的译文');
assert.equal(patched.units[0].notes['中'],patched.units[0].reading.zh);
assert.equal(patched.units[0].reading.ownerEdited,true);
assert.deepEqual(patched.analyses,original.analyses);
assert.deepEqual(patched.units[0].tokens,original.units[0].tokens);
assert.deepEqual(patched.units[0].analyses,original.units[0].analyses);
assert.deepEqual(patched.german,original.german);
assert.deepEqual(patched.units.slice(1),original.units.slice(1));
assert.notEqual(original.units[0].reading.zh,'馆主自行修改的译文');
assert.throws(()=>model.validate(backup,'symposium'));
assert.throws(()=>model.validate({...backup,version:2},'parmenides'));
assert.throws(()=>model.validate({...backup,units:{__proto__:null,'1':{...backup.units[1],reading:{zh:3}}}},'parmenides'));
assert.throws(()=>model.patchPage(original,{...backup,work:'symposium'}));
const wrong=JSON.parse(JSON.stringify(backup));wrong.units[1].greek+='ἕν';
assert.throws(()=>model.patchPage(original,wrong));
const invalid=JSON.parse(JSON.stringify(backup));invalid.units[1].ref='166c';
assert.throws(()=>model.patchPage(original,invalid));
console.log('Editor backup, work isolation, source matching and morphology preservation: passed');
